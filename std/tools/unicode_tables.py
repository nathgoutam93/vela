"""Regenerate the Unicode tables at the end of std/unicode.vl.

    python3 std/tools/unicode_tables.py UCD_DIR

UCD_DIR holds the Unicode Character Database files of the version below:
UnicodeData.txt, CaseFolding.txt, PropList.txt and DerivedCoreProperties.txt,
from https://www.unicode.org/Public/15.1.0/ucd/ (a mirror:
https://github.com/unicode-org/unicodetools, unicodetools/data/ucd/15.1.0).
Their SHA-256 digests must be the ones below, so the tables can be
regenerated exactly. Everything after the marker line in std/unicode.vl is
replaced; the code before it is written by hand.

The data is Unicode's, under the Unicode License v3
(https://www.unicode.org/license.txt).
"""
import hashlib
import sys
from pathlib import Path

VERSION = '15.1.0'
DIGESTS = {
    'UnicodeData.txt': '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86',
    'CaseFolding.txt': '4e55acfdc32825a22e87670e9056a3bf94ad7c5400065778e9e10f8314372bcf',
    'PropList.txt': '05672956317b6296bc2ec3d6cef1f6452b57ff4f2efc6dc55b0a19277d5fcfd1',
    'DerivedCoreProperties.txt': 'f55d0db69123431a7317868725b1fcbf1eab6b265d756d1bd7f0f6d9f9ee108b',
}
MARKER = '// ---- Generated by std/tools/unicode_tables.py from the Unicode Character Database: do not edit below ----'
TARGET = Path(__file__).resolve().parent.parent / 'unicode.vl'
# The order of the categories' numbers in the category table.
CATEGORIES = ['Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Mn', 'Mc', 'Me', 'Nd', 'Nl', 'No', 'Pc', 'Pd', 'Ps', 'Pe', 'Pi', 'Pf', 'Po',
              'Sm', 'Sc', 'Sk', 'So', 'Zs', 'Zl', 'Zp', 'Cc', 'Cf', 'Cs', 'Co', 'Cn']

def read(ucd, name):
    data = (ucd / name).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != DIGESTS[name]:
        sys.exit(f'{name}: SHA-256 {digest}, expected {DIGESTS[name]} (Unicode {VERSION})')
    return data.decode('utf-8')


def categories(text):
    cat = ['Cn'] * 0x110000
    first = None
    for line in text.splitlines():
        f = line.split(';')
        cp = int(f[0], 16)
        if f[1].endswith(', First>'):
            first = cp
            continue
        if f[1].endswith(', Last>'):
            for c in range(first, cp + 1):
                cat[c] = f[2]
            continue
        cat[cp] = f[2]
    return cat


def property_set(text, name):
    out = set()
    for line in text.splitlines():
        line = line.split('#')[0].strip()
        if not line:
            continue
        cps, prop = [x.strip() for x in line.split(';')[:2]]
        if prop != name:
            continue
        lo, _, hi = cps.partition('..')
        out.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return out


def foldings(text):
    simple, full, special = {}, {}, set()
    for line in text.splitlines():
        line = line.split('#')[0].strip()
        if not line:
            continue
        code, status, mapping = [x.strip() for x in line.split(';')[:3]]
        cp = int(code, 16)
        to = [int(x, 16) for x in mapping.split()]
        if status in ('C', 'S'):
            simple[cp] = to[0]
        if status == 'S':
            special.add(cp)
        if status == 'F':
            full[cp] = to
    # Full folding is F where there is one, else C. An S mapping always has
    # an F beside it, so full folding is F, else the simple folding.
    assert special <= set(full)
    return simple, full


def runs(pred):
    out, start = [], None
    for cp in range(0x110001):
        inside = cp < 0x110000 and pred(cp)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


# The tables are module constants (TL-108): flat Int arrays, which compile to
# static data and are built once, on first use.
def const_array(name, doc, xs):
    out = [doc, f'const {name}: [Int] = [']
    for i in range(0, len(xs), 8):
        out.append('    ' + ', '.join(f'{x:#x}' for x in xs[i:i + 8]) + (',' if i + 8 < len(xs) else ''))
    out += [']', '']
    return out


def flat_ranges(pred):
    out = []
    for lo, hi in runs(pred):
        out += [lo, hi]
    return out


def fold_records(simple):
    """Runs of code points each folding by the same offset (kind 0), or
    pairs where every even (1) or odd (2) code point folds to the one after
    it and the others to themselves, as in Latin Extended-A: [first, last,
    kind, offset] each."""
    keys = sorted(simple)
    out, i = [], 0
    while i < len(keys):
        c = keys[i]
        p = c
        while simple.get(p) == p + 1 and (p + 1) not in simple:
            p += 2
        if p - c >= 4:  # two pairs or more
            out += [c, p - 1, 1 if c % 2 == 0 else 2, 0]
            while i < len(keys) and keys[i] < p:
                i += 1
            continue
        d = simple[c] - c
        j = i
        while j + 1 < len(keys) and keys[j + 1] == keys[j] + 1 and simple[keys[j + 1]] - keys[j + 1] == d:
            j += 1
        out += [c, keys[j], 0, d]
        i = j + 1
    return out


def generate(ucd):
    cat = categories(read(ucd, 'UnicodeData.txt'))
    simple, full = foldings(read(ucd, 'CaseFolding.txt'))
    props = read(ucd, 'PropList.txt')
    white = property_set(props, 'White_Space')
    join = property_set(props, 'Join_Control')
    alpha = property_set(read(ucd, 'DerivedCoreProperties.txt'), 'Alphabetic')

    def word(cp):
        return cp in alpha or cat[cp] in ('Mn', 'Mc', 'Me', 'Nd', 'Pc') or cp in join

    out = [MARKER, f'// Unicode {VERSION}.', '']
    out += ['// The version of Unicode the tables below are of.', 'fn unicode_version() -> Str {',
            f'    return "{VERSION}"', '}', '']
    out += ['// The general categories, in the order of their numbers below.',
            'fn category_names() -> Str {', '    return "' + ''.join(CATEGORIES) + '"', '}', '']
    starts, numbers = [], []
    start = 0
    for cp in range(1, 0x110001):
        if cp == 0x110000 or cat[cp] != cat[start]:
            starts.append(start)
            numbers.append(CATEGORIES.index(cat[start]))
            start = cp
    out += const_array('LATIN1_CATEGORIES', '// The category numbers of the first 256 code points.',
                       [CATEGORIES.index(cat[c]) for c in range(256)])
    out += const_array('CATEGORY_STARTS', '// Runs of code points of one category: where each starts (the next\n'
                       '// starts where it ends), and, in CATEGORY_NUMBERS, its category.', starts)
    out += const_array('CATEGORY_NUMBERS', '// The category of each run in CATEGORY_STARTS.', numbers)
    out += const_array('ALPHABETIC_RANGES', '// The code points with the Alphabetic property: [lo, hi, ...].', flat_ranges(lambda c: c in alpha))
    out += const_array('WHITE_SPACE_RANGES', '// The code points with the White_Space property: [lo, hi, ...].', flat_ranges(lambda c: c in white))
    out += const_array('WORD_RANGES', '// Word characters as UTS #18 defines \\w (Alphabetic, a mark, a decimal\n'
                       '// digit, a connector punctuation or Join_Control): [lo, hi, ...].', flat_ranges(word))
    out += const_array('FOLD_RUNS', '// Simple case folding (CaseFolding.txt\'s C and S mappings) in runs:\n'
                       '// [first, last, kind, offset, ...]; kind 0: each by the offset, 1 or 2:\n'
                       '// each even or odd code point to the next one.', fold_records(simple))
    full_records = []
    for cp in sorted(full):
        full_records += [cp] + full[cp] + [0] * (3 - len(full[cp]))
    out += const_array('FULL_FOLDS', '// Code points whose full case folding is more than one (F mappings):\n'
                       '// [cp, a, b, c, ...], 0 after the last.', full_records)
    return [line for line in out][:-1]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    text = TARGET.read_text()
    head = text.split(MARKER)[0].rstrip('\n')
    TARGET.write_text(head + '\n\n' + '\n'.join(generate(Path(sys.argv[1]))) + '\n')


if __name__ == '__main__':
    main()
