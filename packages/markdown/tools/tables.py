"""Write packages/markdown/tables.vl: the Unicode and HTML data CommonMark needs.

    python3 packages/markdown/tools/tables.py > packages/markdown/tables.vl

From Python's own unicodedata and html.entities, so the Unicode version is
the generating Python's (recorded in the output).
"""
import html.entities
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def vela_str(s):
    b = []
    for byte in s.encode('utf-8'):
        c = chr(byte)
        if c == '"' or c == '\\':
            b.append('\\' + c)
        elif 32 <= byte < 127:
            b.append(c)
        else:
            b.append(None)
    if None in b:
        # Escapes Vela has for bytes are few: spell a non-ASCII value as its UTF-8 text.
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'
    return '"' + ''.join(b) + '"'


def arms(pairs):
    return [f'        {lo} => true' if lo == hi else f'        {lo}..={hi} => true' for lo, hi in pairs]


out = ['// Generated by tools/tables.py from Python ' + sys.version.split()[0] + ', Unicode ' +
       unicodedata.unidata_version + ': do not edit.',
       '// Unicode punctuation and whitespace as CommonMark defines them, full',
       '// case folding for link labels, and the HTML5 named character references.',
       '']
punct = ranges(lambda cp: unicodedata.category(chr(cp))[0] in 'PS')
out.append('// A character in a Unicode P (punctuation) or S (symbol) category.')
out.append('pub fn punctuation(cp: Int) -> Bool {')
out.append('    return match cp {')
out += arms(punct)
out += ['        _ => false', '    }', '}', '']
space = ranges(lambda cp: unicodedata.category(chr(cp)) == 'Zs' or cp in (9, 10, 12, 13))
out.append('// A character in the Zs category, or tab, line feed, form feed or carriage return.')
out.append('pub fn whitespace(cp: Int) -> Bool {')
out.append('    return match cp {')
out += arms(space)
out += ['        _ => false', '    }', '}', '']
out.append('// The full case folding of a character, or "" when it folds to itself.')
out.append('pub fn fold(cp: Int) -> Str {')
out.append('    return match cp {')
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    f = c.casefold()
    if f != c:
        out.append(f'        {cp} => {vela_str(f)}')
out += ['        _ => ""', '    }', '}', '']
out.append('// The text a named character reference such as "amp" stands for, or "".')
out.append('pub fn entity(name: Str) -> Str {')
out.append('    return match name {')
for name in sorted(html.entities.html5):
    if name.endswith(';'):
        out.append(f'        {vela_str(name[:-1])} => {vela_str(html.entities.html5[name])}')
out += ['        _ => ""', '    }', '}']
print('\n'.join(out))
