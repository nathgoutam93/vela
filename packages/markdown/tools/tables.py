"""Write packages/markdown/tables.vl: the HTML5 named character references.

    python3 packages/markdown/tools/tables.py > packages/markdown/tables.vl

From Python's own html.entities (the generating Python's version is recorded
in the output). Unicode punctuation, whitespace and case folding come from
std/unicode.
"""
import html.entities
import sys


def vela_str(s):
    b = []
    for byte in s.encode('utf-8'):
        c = chr(byte)
        if c == '"' or c == '\\':
            b.append('\\' + c)
        elif 32 <= byte < 127:
            b.append(c)
        else:
            b.append(None)
    if None in b:
        # Escapes Vela has for bytes are few: spell a non-ASCII value as its UTF-8 text.
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'
    return '"' + ''.join(b) + '"'


out = ['// Generated by tools/tables.py from Python ' + sys.version.split()[0] + ': do not edit.',
       '// The HTML5 named character references. (Unicode punctuation, whitespace',
       '// and case folding come from std/unicode.)',
       '']
# The names are matched by first letter, then by length, and only then by
# text: a match on Str compared arm by arm until TL-107, and small matches
# still keep each function small.
entities = {}
for name in sorted(html.entities.html5):
    if name.endswith(';'):
        entities.setdefault(name[0], {}).setdefault(len(name) - 1, []).append(name[:-1])
out.append('// The text a named character reference such as "amp" stands for, or "".')
out.append('pub fn entity(name: Str) -> Str {')
out.append('    if len(name) == 0 {')
out.append('        return ""')
out.append('    }')
out.append('    return match name[0] {')
for first in sorted(entities):
    out.append(f"        '{first}' => entity_{first}(name)")
out += ['        _ => ""', '    }', '}']
for first, by_length in sorted(entities.items()):
    out += ['', f'fn entity_{first}(name: Str) -> Str {{', '    return match len(name) {']
    for length, names in sorted(by_length.items()):
        out.append(f'        {length} => match name {{')
        for name in names:
            out.append(f'            {vela_str(name)} => {vela_str(html.entities.html5[name + ";"])}')
        out += ['            _ => ""', '        }']
    out += ['        _ => ""', '    }', '}']
print('\n'.join(out))
