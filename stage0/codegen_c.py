"""Stage 0 C code generator: a checked AST in, C source out.

Top-level statements run in order inside C's `main`.

Each operation becomes one C statement that stores its result in a fresh
temporary (`_t1`, `_t2`, ...). For `print(1 + 2 * 3)`:

    int64_t _t1 = vela_mul(2, 3, "a.vl:1:13");
    int64_t _t2 = vela_add(1, _t1, "a.vl:1:9");
    vela_print_int(_t2);

C does not say in which order a function's arguments are evaluated, so
`vela_add(vela_div(...), vela_div(...))` could run either division first,
and if both divide by zero, which panic you see would depend on the C
compiler. Emitting one statement per operation, in tree order, makes Vela's
order left to right on every compiler.

Arithmetic goes through runtime functions (vela_rt.h) instead of C's `+`,
because signed overflow in C is undefined behaviour; the runtime checks for
it and panics. The string argument is the operator's source position, used
in the panic message.
"""
from __future__ import annotations

import os

from ast_nodes import Binary, Call, Expr, IntLit, Name, Program, Stmt, Unary

ARITHMETIC = {
    "+": "vela_add",
    "-": "vela_sub",
    "*": "vela_mul",
    "/": "vela_div",
    "%": "vela_rem",
}


def generate(program: Program, filename: str) -> str:
    gen = CodeGen(filename)
    for stmt in program.stmts:
        gen.stmt(stmt)
    return "\n".join([
        "// Generated by the Vela stage 0 compiler. Do not edit.",
        '#include "vela_rt.h"',
        "",
        "int main(void) {",
        *gen.lines,
        "    return 0;",
        "}",
        "",
    ])


class CodeGen:
    def __init__(self, filename: str):
        self.filename = filename
        self.lines: list[str] = []
        self.temps = 0

    def emit(self, line: str) -> None:
        self.lines.append("    " + line)

    def new_temp(self) -> str:
        # C reserves names starting with `_` only at file scope (and `_` plus
        # a capital or a second `_` everywhere), so `_t1` in a block is ours.
        self.temps += 1
        return f"_t{self.temps}"

    def loc(self, e: Expr) -> str:
        return c_string(f"{self.filename}:{e.line}:{e.col}")

    def stmt(self, stmt: Stmt) -> None:
        self.emit(f"// line {stmt.expr.line}")
        self.expr(stmt.expr)

    def expr(self, e: Expr) -> str | None:
        """Emit code for `e` and return a C expression for its value.

        The returned expression is always a literal or a temporary, so using
        it has no side effects and its position in the C does not matter.
        Returns None for a call that produces no value.
        """
        if isinstance(e, IntLit):
            return str(e.value)
        if isinstance(e, Unary):
            operand = self.expr(e.operand)
            return self.store(f"vela_neg({operand}, {self.loc(e)})")
        if isinstance(e, Binary):
            left = self.expr(e.left)
            right = self.expr(e.right)
            return self.store(f"{ARITHMETIC[e.op]}({left}, {right}, {self.loc(e)})")
        if isinstance(e, Call):
            assert isinstance(e.callee, Name) and e.callee.name == "print"
            arg = self.expr(e.args[0])
            self.emit(f"vela_print_int({arg});")
            return None
        raise AssertionError(f"cannot generate code for {e!r}")

    def store(self, c_expr: str) -> str:
        temp = self.new_temp()
        self.emit(f"int64_t {temp} = {c_expr};")
        return temp


def c_string(text: str) -> str:
    """A C string literal for any text, such as a file name."""
    out = []
    for byte in os.fsencode(text):
        ch = chr(byte)
        if ch in '"\\?':
            # `?` too: with -std=c11, `??/` and friends are trigraphs.
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")  # octal escapes stop after 3 digits
    return '"' + "".join(out) + '"'
