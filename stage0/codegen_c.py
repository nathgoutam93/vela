"""Stage 0 C code generator: a checked AST in, C source out.

Each Vela function becomes a C function named `f_<name>`, and C's `main`
calls `f_main`. Locals become C locals named `v_<name>`. Types are laid out
by c_layout.py.

Each operation becomes one C statement that stores its result in a fresh
temporary (`_t1`, `_t2`, ...). For `print(1 + 2 * 3)`:

    int64_t _t1 = vela_mul(2, 3, "a.vl:2:17");
    int64_t _t2 = vela_add(1, _t1, "a.vl:2:13");
    vela_print_int(_t2);

C does not say in which order a function's arguments are evaluated, so
`vela_add(f(), g())` could call either function first. Emitting one
statement per operation, in tree order, makes Vela's order left to right on
every compiler. It also gives `&&`, `||` and loop conditions a natural place
for the statements they must run only sometimes, or on every iteration.

Arithmetic goes through runtime functions (vela_rt.h) instead of C's `+`,
because signed overflow in C is undefined behaviour; the runtime checks for
it and panics. The string argument is the operator's source position, used
in the panic message.
"""
from __future__ import annotations

import os

from ast_nodes import (
    Arm, Assign, Binary, Block, BoolLit, Break, Call, Continue, Expr, ExprStmt, Field, FnDecl,
    For, ForRange, If, IntLit, Let, Match, MatchStmt, Name, Pattern, PBind, PLit, Program,
    PVariant, PWild, Return, Stmt, StrLit, StructLit, Unary,
)
from c_layout import Layout
from checker import Local
from typesys import BOOL, INT, STR, EnumType, StructType, Type

ARITHMETIC = {
    "+": "vela_add",
    "-": "vela_sub",
    "*": "vela_mul",
    "/": "vela_div",
    "%": "vela_rem",
}

PRINT = {INT: "vela_print_int", BOOL: "vela_print_bool", STR: "vela_print_str"}


def generate(program: Program, filename: str) -> str:
    layout = Layout([d.type for d in program.types], list(program.table.instances.values()))
    out = [
        "// Generated by the Vela stage 0 compiler. Do not edit.",
        '#include "vela_rt.h"',
        "",
    ]
    types = layout.definitions()
    if types:
        out += [*types, ""]
    # Declare every function first, so each can call any other, in any order.
    out += [prototype(f, layout) + ";" for f in program.fns]
    for f in program.fns:
        out += ["", *FunctionGen(filename, layout).function(f)]
    out += [
        "",
        "int main(void) {",
        "    f_main();",
        "    return 0;",
        "}",
        "",
    ]
    return "\n".join(out)


def prototype(f: FnDecl, layout: Layout, names: list[str] | None = None) -> str:
    """`int64_t f_fib(int64_t v_n)`, or with no names, `int64_t f_fib(int64_t)`."""
    params = [
        layout.c_type(t) + (f" {names[i]}" if names else "") for i, t in enumerate(f.sig.params)
    ]
    return f"{layout.c_type(f.sig.result)} f_{f.name}({', '.join(params) or 'void'})"


class FunctionGen:
    """Generates one function. Temporaries and C names are per function."""

    def __init__(self, filename: str, layout: Layout):
        self.filename = filename
        self.layout = layout
        self.lines: list[str] = []
        self.depth = 1  # indentation level
        self.temps = 0
        self.names: dict[Local, str] = {}
        self.used: set[str] = set()

    def emit(self, line: str) -> None:
        self.lines.append("    " * self.depth + line)

    def new_temp(self) -> str:
        # C reserves names starting with `_` only at file scope (and `_` plus
        # a capital or a second `_` everywhere), so `_t1` in a block is ours.
        self.temps += 1
        return f"_t{self.temps}"

    def c_type(self, t: Type | None) -> str:
        return self.layout.c_type(t)

    def store(self, ty: Type, c_expr: str) -> str:
        temp = self.new_temp()
        self.emit(f"{self.c_type(ty)} {temp} = {c_expr};")
        return temp

    def box(self, ty: Type, value: str) -> str:
        """Copy a value to the heap; returns the pointer (a temporary)."""
        c = self.c_type(ty)
        temp = self.new_temp()
        self.emit(f"{c} *{temp} = vela_alloc(sizeof({c}));")
        self.emit(f"*{temp} = {value};")
        return temp

    def local(self, local: Local) -> str:
        """The C name of a local: `v_x`, or `v_x_2` for a second `x`.

        Every local in a function gets its own C name, even when an inner
        `x` shadows an outer one. In C, `int64_t v_x = v_x;` would read the
        new, uninitialised `v_x`, whereas Vela's `let x = x` means the outer
        one.
        """
        if local not in self.names:
            base = name = f"v_{local.name}"
            n = 2
            while name in self.used:
                name, n = f"{base}_{n}", n + 1
            self.used.add(name)
            self.names[local] = name
        return self.names[local]

    def loc(self, e: Expr) -> str:
        return c_string(os.fsencode(f"{self.filename}:{e.line}:{e.col}"))

    # ---- Functions and statements ----

    def function(self, f: FnDecl) -> list[str]:
        names = [self.local(p.local) for p in f.params]
        for stmt in f.body.stmts:
            self.stmt(stmt)
        return [prototype(f, self.layout, names) + " {", *self.lines, "}"]

    def block(self, block: Block) -> None:
        self.depth += 1
        for stmt in block.stmts:
            self.stmt(stmt)
        self.depth -= 1

    def stmt(self, s: Stmt) -> None:
        if isinstance(s, Block):
            self.emit("{")
            self.block(s)
            self.emit("}")
            return
        self.emit(f"// line {s.expr.line if isinstance(s, ExprStmt) else s.line}")
        if isinstance(s, ExprStmt):
            assert isinstance(s.expr, Call)
            self.call_stmt(s.expr)
        elif isinstance(s, Let):
            value = self.expr(s.value)
            self.emit(f"{self.c_type(s.local.ty)} {self.local(s.local)} = {value};")
        elif isinstance(s, Assign):
            self.assign(s)
        elif isinstance(s, If):
            self.if_stmt(s)
        elif isinstance(s, For):
            # Any statements the condition needs must run on every
            # iteration, so the test goes inside the loop.
            self.emit("for (;;) {")
            if s.cond is not None:
                self.depth += 1
                cond = self.expr(s.cond)
                self.emit(f"if (!{cond}) break;")
                self.depth -= 1
            self.block(s.body)
            self.emit("}")
        elif isinstance(s, ForRange):
            start = self.expr(s.start)
            end = self.expr(s.end)
            if isinstance(s.end, (Name, Field)):
                # The range is fixed when the loop starts, even if the body
                # assigns to the variable it ends at, so copy the variable.
                # (Literals and temporaries never change.)
                end = self.store(INT, end)
            i = self.new_temp()
            self.emit(f"for (int64_t {i} = {start}; {i} < {end}; {i}++) {{")
            self.depth += 1
            self.emit(f"int64_t {self.local(s.local)} = {i};")
            self.depth -= 1
            self.block(s.body)
            self.emit("}")
        elif isinstance(s, Break):
            self.emit("break;")
        elif isinstance(s, Continue):
            self.emit("continue;")
        elif isinstance(s, Return):
            if s.value is None:
                self.emit("return;")
            else:
                self.emit(f"return {self.expr(s.value)};")
        elif isinstance(s, MatchStmt):
            self.match(s.scrutinee, s.arms, self.arm_stmt)
        else:
            raise AssertionError(f"cannot generate code for {s!r}")

    def if_stmt(self, s: If) -> None:
        cond = self.expr(s.cond)
        self.emit(f"if ({cond}) {{")
        self.block(s.then)
        if s.else_ is None:
            self.emit("}")
            return
        self.emit("} else {")
        if isinstance(s.else_, If):
            # `else if`'s condition may need statements of its own, which
            # must only run when the first condition was false.
            self.depth += 1
            self.if_stmt(s.else_)
            self.depth -= 1
        else:
            self.block(s.else_)
        self.emit("}")

    def assign(self, s: Assign) -> None:
        value = self.expr(s.value)
        target = s.target
        if isinstance(target, Name):
            self.emit(f"{self.local(target.ref)} = {value};")
            return
        assert isinstance(target, Field)
        owner = target.obj.ty
        base = self.place(target.obj)
        if self.layout.is_boxed(owner, target.name):
            # Never write into a box: other values may share it. Point the
            # field at a new box holding the new value instead.
            value = self.box(target.ty, value)
        self.emit(f"{base}.m_{target.name} = {value};")

    def place(self, e: Expr) -> str:
        """A C lvalue for a variable or a field path that is about to be
        written through, such as `v_p.m_pos` in `p.pos.x = 1`."""
        if isinstance(e, Name):
            return self.local(e.ref)
        assert isinstance(e, Field)
        base = self.place(e.obj)
        member = f"{base}.m_{e.name}"
        if not self.layout.is_boxed(e.obj.ty, e.name):
            return member
        # Copy before write: the box may be shared with other values (a
        # copy of a struct copies the pointer, not the box), so give this
        # value a box of its own before changing what is inside. M5's
        # reference counts will make the copy happen only when it is shared.
        copy = self.box(e.ty, f"*{member}")
        self.emit(f"{member} = {copy};")
        return f"(*{member})"

    # ---- Match ----

    def match(self, scrutinee: Expr, arms: list[Arm], body) -> None:
        """An if / else-if chain, one test per arm, in order.

        The checker has proved the arms exhaustive, so if every other arm
        failed the last one must match: it becomes a plain `else`. That
        also tells the C compiler that some arm always runs.
        """
        value = self.expr(scrutinee)
        t = scrutinee.ty
        for i, arm in enumerate(arms):
            last = i == len(arms) - 1
            if last:
                self.emit("} else {" if i else "{")
            else:
                cond = " && ".join(self.tests(arm.pattern, value, t)) or "true"
                self.emit(f"{'} else if' if i else 'if'} ({cond}) {{")
            self.depth += 1
            for local, path in self.bindings(arm.pattern, value, t):
                self.emit(f"{self.c_type(local.ty)} {self.local(local)} = {path};")
            body(arm)
            self.depth -= 1
        self.emit("}")

    def arm_stmt(self, arm: Arm) -> None:
        if isinstance(arm.body, Block):
            for stmt in arm.body.stmts:
                self.stmt(stmt)
        else:
            self.stmt(arm.body)

    def payload(self, path: str, enum: EnumType, variant, i: int) -> str:
        member = f"{path}.as.m_{variant.name}._{i}"
        return f"(*{member})" if self.layout.is_boxed(enum, variant.name, i) else member

    def tests(self, p: Pattern, path: str, t: Type) -> list[str]:
        """C conditions, all of which hold when the value at `path` matches `p`.

        They are joined with C's `&&`, which stops at the first false one,
        so a payload is only looked at once its tag is known to be right.
        """
        if isinstance(p, (PWild, PBind)):
            return []
        if isinstance(p, PLit):
            lit = p.value
            if isinstance(lit, BoolLit):
                return [path if lit.value else f"!{path}"]
            if isinstance(lit, StrLit):
                return [f"vela_str_eq({path}, VELA_STR({c_string(lit.value)}, {len(lit.value)}))"]
            return [f"{path} == {lit.value}"]
        assert isinstance(p, PVariant)
        enum, variant = p.ref
        out = [f"{path}.tag == {self.layout.tag(enum, variant.name)}"]
        for i, sub in enumerate(p.args or []):
            out += self.tests(sub, self.payload(path, enum, variant, i), variant.payload[i])
        return out

    def bindings(self, p: Pattern, path: str, t: Type) -> list[tuple[Local, str]]:
        if isinstance(p, PBind):
            return [(p.local, path)]
        if isinstance(p, PVariant):
            enum, variant = p.ref
            out = []
            for i, sub in enumerate(p.args or []):
                out += self.bindings(sub, self.payload(path, enum, variant, i), variant.payload[i])
            return out
        return []

    # ---- Expressions ----

    def expr(self, e: Expr) -> str | None:
        """Emit code for `e` and return a C expression for its value.

        The returned expression is always a literal, a variable, a
        temporary, or a field of one of those, so using it has no side
        effects and its position in the C does not matter. Returns None for
        a call that produces no value.
        """
        if isinstance(e, IntLit):
            return str(e.value)
        if isinstance(e, BoolLit):
            return "true" if e.value else "false"
        if isinstance(e, StrLit):
            return f"VELA_STR({c_string(e.value)}, {len(e.value)})"
        if isinstance(e, Name):
            if isinstance(e.ref, Local):
                return self.local(e.ref)
            enum, variant = e.ref  # `None`
            return self.enum_value(enum, variant, [])
        if isinstance(e, Unary):
            operand = self.expr(e.operand)
            if e.op == "-":
                return self.store(INT, f"vela_neg({operand}, {self.loc(e)})")
            return self.store(BOOL, f"!{operand}")
        if isinstance(e, Binary):
            return self.binary(e)
        if isinstance(e, Call):
            if isinstance(e.target, tuple):
                enum, variant = e.target
                args = [self.expr(a) for a in e.args]
                return self.enum_value(enum, variant, args)
            call = self.call(e)
            if e.ty is None:
                self.emit(call + ";")
                return None
            return self.store(e.ty, call)
        if isinstance(e, Field):
            if e.variant is not None:
                enum, variant = e.variant
                return self.enum_value(enum, variant, [])
            obj = self.expr(e.obj)
            member = f"{obj}.m_{e.name}"
            return f"(*{member})" if self.layout.is_boxed(e.obj.ty, e.name) else member
        if isinstance(e, StructLit):
            return self.struct_value(e)
        if isinstance(e, Match):
            result = self.new_temp()
            self.emit(f"{self.c_type(e.ty)} {result};")
            self.match(e.scrutinee, e.arms,
                       lambda arm: self.emit(f"{result} = {self.expr(arm.body)};"))
            return result
        raise AssertionError(f"cannot generate code for {e!r}")

    def enum_value(self, enum: EnumType, variant, args: list[str]) -> str:
        """A temporary holding `(t_Expr){ .tag = ..., .as.m_Add = { ._0 = ..., ._1 = ... } }`."""
        fields = [f".tag = {self.layout.tag(enum, variant.name)}"]
        if args:
            values = []
            for i, (arg, pt) in enumerate(zip(args, variant.payload)):
                if self.layout.is_boxed(enum, variant.name, i):
                    arg = self.box(pt, arg)
                values.append(f"._{i} = {arg}")
            fields.append(f".as.m_{variant.name} = {{ {', '.join(values)} }}")
        return self.store(enum, f"({self.c_type(enum)}){{ {', '.join(fields)} }}")

    def struct_value(self, e: StructLit) -> str:
        t = e.ty
        assert isinstance(t, StructType)
        values = {}
        for f in e.fields:  # in source order: evaluation is left to right
            value = self.expr(f.value)
            if self.layout.is_boxed(t, f.name):
                value = self.box(t.fields[f.name], value)
            values[f.name] = value
        inits = ", ".join(f".m_{name} = {values[name]}" for name in t.fields)
        return self.store(t, f"({self.c_type(t)}){{ {inits} }}")

    def binary(self, e: Binary) -> str:
        if e.op in ("&&", "||"):
            # Short-circuit: the right side runs only if it can change the
            # answer, so its statements go inside an `if`.
            result = self.new_temp()
            self.emit(f"bool {result} = {self.expr(e.left)};")
            self.emit(f"if ({'' if e.op == '&&' else '!'}{result}) {{")
            self.depth += 1
            self.emit(f"{result} = {self.expr(e.right)};")
            self.depth -= 1
            self.emit("}")
            return result
        left = self.expr(e.left)
        right = self.expr(e.right)
        if e.op in ARITHMETIC:
            return self.store(INT, f"{ARITHMETIC[e.op]}({left}, {right}, {self.loc(e)})")
        operand = e.left.ty
        if operand is STR:
            negate = "!" if e.op == "!=" else ""
            return self.store(BOOL, f"{negate}vela_str_eq({left}, {right})")
        if isinstance(operand, EnumType):
            return self.store(BOOL, f"{left}.tag {e.op} {right}.tag")
        return self.store(BOOL, f"{left} {e.op} {right}")

    def call_stmt(self, e: Call) -> None:
        """A call whose result, if any, is thrown away."""
        if isinstance(e.target, tuple):
            self.expr(e)  # building an enum value has no effect, but its arguments might
        else:
            self.emit(self.call(e) + ";")

    def call(self, e: Call) -> str:
        """Emit the arguments' code and return the C call expression."""
        args = [self.expr(a) for a in e.args]
        if e.target == "print":
            return f"{PRINT[e.args[0].ty]}({args[0]})"
        return f"f_{e.target.name}({', '.join(args)})"


def c_string(data: bytes) -> str:
    """A C string literal for any bytes: a file name or a Vela string."""
    out = []
    for byte in data:
        ch = chr(byte)
        if ch in '"\\?':
            # `?` too: with -std=c11, `??/` and friends are trigraphs.
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")  # octal escapes stop after 3 digits
    return '"' + "".join(out) + '"'
