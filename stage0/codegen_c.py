"""Stage 0 C code generator: a checked AST in, C source out.

Each Vela function becomes a C function named `f_<name>`, and C's `main`
calls `f_main`. Locals become C locals named `v_<name>`. Types are laid out
by c_layout.py. The functions and types of imported modules get their
module's name mixed into their C names (see `mangle` in c_layout.py), so
lexer.next and parser.next are different C functions.

Each operation becomes one C statement that stores its result in a fresh
temporary (`_t1`, `_t2`, ...). For `print(1 + 2 * 3)`:

    int64_t _t1 = vela_mul(2, 3, "a.vl:2:17");
    int64_t _t2 = vela_add(1, _t1, "a.vl:2:13");
    vela_print_int(_t2);

C does not say in which order a function's arguments are evaluated, so
emitting one statement per operation, in tree order, is what makes Vela's
order left to right on every compiler.

Memory (M5). Values of managed types (see c_layout.py) hold references to
reference-counted heap objects. The generator follows one ownership rule:

- An *owned* value holds one reference that somebody must give up: the
  result of a call, a constructor, a concatenation. A *borrowed* value is a
  view of something owned elsewhere: reading a variable, a field or an
  element.
- *Consuming* a value takes its reference: storing it in a variable, field
  or element, passing it to a function, returning it. Consuming a borrowed
  value retains it first (`consume`).
- Every owned temporary and every managed local is recorded in a *cleanup
  frame*. Frames follow the program's structure: a statement's temporaries
  are released when the statement ends, a block's locals when the block
  ends. `return`, `break` and `continue` release every frame they leave.

Changing a value in place (an element, a field behind a box, `push`) first
makes the object unique: if anything else shares it, it is copied. That is
copy-on-write, and it is what makes values behave as values.
"""
