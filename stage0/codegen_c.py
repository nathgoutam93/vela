def generate(program: list[Module], table: TypeTable) -> str:
    """C for a checked program: its modules in dependency order, and the
    checker's table of the Option, Result, array and map types it uses."""
    decls = [d for m in program for d in m.program.types]  # type: ignore[union-attr]
    fns = [(m, f) for m in program for f in m.program.fns]  # type: ignore[union-attr]
    elements = []
    for t in list(table.arrays.keys()) + [x for kv in table.maps.keys() for x in kv]:
        if t not in elements:
            elements.append(t)
    layout = Layout([d.type for d in decls], list(table.instances.values()), elements)
    out = [
        "// Generated by the Vela stage 0 compiler. Do not edit.",
        '#include "vela_rt.h"',
        "",
    ]
    types = layout.definitions()
    if types:
        out += [*types, ""]
    # Declare every function first, so each can call any other, in any order.
    out += [prototype(f, layout) + ";" for _, f in fns]
    for m, f in fns:
        out += ["", *FunctionGen(m.path, layout).function(f)]
    out += [
        "",
        "int main(int argc, char **argv) {",
        "    vela_init(argc, argv);",
        "    f_main();",
        "    return 0;",
        "}",
        "",
    ]
    return "\n".join(out)


def prototype(f: FnDecl, layout: Layout, names: list[str] | None = None) -> str:
    """`int64_t f_fib(int64_t v_n)`, or with no names, `int64_t f_fib(int64_t)`."""
    params = [
        layout.c_type(t) + (f" {names[i]}" if names else "") for i, t in enumerate(f.sig.params)
    ]
    return f"{layout.c_type(f.sig.result)} {fn_name(f)}({', '.join(params) or 'void'})"


def fn_name(f: FnDecl) -> str:
    return "f_" + mangle(f.module, f.name)


@dataclass
class Value:
    """The C expression for a value, and whether it holds a reference."""
    c: str
    ty: Type | None
    owned: bool = False
    static: bool = False  # a Str literal: never counted, so free to copy


@dataclass
class Frame:
    """Values to release when a part of the program ends."""
    kind: str  # "function", "block", "body" (of a loop), "arm", "stmt" or "branch"
    items: list[tuple[str, Type]] = field(default_factory=list)

    @property
    def scope(self) -> bool:
        """Whether locals declared here belong to this frame."""
        return self.kind in ("function", "block", "body", "arm")


class FunctionGen:
    """Generates one function. Temporaries and C names are per function."""

    def __init__(self, filename: str, layout: Layout):
        self.filename = filename
        self.layout = layout
        self.lines: list[str] = []
        self.depth = 1  # indentation level
        self.temps = 0
        self.names: dict[Local, str] = {}
        self.used: set[str] = set()
        self.frames: list[Frame] = []
        self.dead = False  # true right after a return, break or continue

    # ---- Output ----

    def emit(self, line: str | None) -> None:
        if line is not None:
            self.lines.append("    " * self.depth + line)

    def open(self, line: str) -> None:
        """Emit a line ending in `{` and indent."""
        self.emit(line)
        self.depth += 1

    def close(self, line: str = "}") -> None:
        """Dedent and emit a line starting with `}`. The code after it may be
        reachable again (from another branch)."""
        self.depth -= 1
        self.emit(line)
        self.dead = False

    def new_temp(self) -> str:
        # C reserves names starting with `_` only at file scope (and `_` plus
        # a capital or a second `_` everywhere), so `_t1` in a block is ours.
        self.temps += 1
        return f"_t{self.temps}"

    def c_type(self, t: Type | None) -> str:
        return self.layout.c_type(t)

    def managed(self, t: Type | None) -> bool:
        return self.layout.managed(t)

    def loc(self, e: object) -> str:
        return c_string(os.fsencode(f"{self.filename}:{e.line}:{e.col}"))  # type: ignore[attr-defined]

    def local(self, local: Local) -> str:
        """The C name of a local: `v_x`, or `v_x_2` for a second `x`.

        Every local in a function gets its own C name, even when an inner
        `x` shadows an outer one. In C, `int64_t v_x = v_x;` would read the
        new, uninitialised `v_x`, whereas Vela's `let x = x` means the outer
        one.
        """
        if local not in self.names:
            base = name = f"v_{local.name}"
            n = 2
            while name in self.used:
                name, n = f"{base}_{n}", n + 1
            self.used.add(name)
            self.names[local] = name
        return self.names[local]

    # ---- Ownership ----

    def push_frame(self, kind: str) -> None:
        self.frames.append(Frame(kind))

    def pop_frame(self) -> None:
        frame = self.frames.pop()
        if not self.dead:
            self.release_frame(frame)

    def release_frame(self, frame: Frame) -> None:
        for c, ty in reversed(frame.items):
            self.emit(self.layout.release(ty, c))

    def own(self, c: str, ty: Type | None) -> Value:
        """Record a new owned temporary in the innermost frame."""
        if self.managed(ty):
            self.frames[-1].items.append((c, ty))
        return Value(c, ty, owned=True)

    def store(self, ty: Type | None, c_expr: str) -> Value:
        """Put an expression's value in a fresh temporary, owned."""
        temp = self.new_temp()
        self.emit(f"{self.c_type(ty)} {temp} = {c_expr};")
        return self.own(temp, ty)

    def scalar(self, ty: Type, c_expr: str) -> str:
        """A temporary for a value with no references (Int, Bool, Byte...)."""
        temp = self.new_temp()
        self.emit(f"{self.c_type(ty)} {temp} = {c_expr};")
        return temp

    def addr(self, c_type: str, value: str) -> str:
        """The address of a copy of `value`, for runtime functions that take
        an element by pointer. (A compound literal `&(T){value}` would only
        work for scalars: for a struct it initialises the first member.)"""
        temp = self.new_temp()
        self.emit(f"{c_type} {temp} = {value};")
        return "&" + temp

    def consume(self, v: Value) -> str:
        """Take ownership of a value; returns a C expression for it."""
        if not self.managed(v.ty) or v.static:
            return v.c
        if v.owned:
            for frame in reversed(self.frames):
                if (v.c, v.ty) in frame.items:
                    frame.items.remove((v.c, v.ty))
                    break
            return v.c
        if not re.fullmatch(r"v_\w+|_t\d+", v.c):
            # Copy a field or element path into a temporary first, so later
            # changes to where it came from cannot change the copy.
            temp = self.new_temp()
            self.emit(f"{self.c_type(v.ty)} {temp} = {v.c};")
            v = Value(temp, v.ty)
        self.emit(self.layout.retain(v.ty, v.c))
        return v.c

    def declare(self, local: Local, value: str) -> str:
        """Declare a local holding an owned value; it is released when its
        scope ends."""
        name = self.local(local)
        self.emit(f"{self.c_type(local.ty)} {name} = {value};")
        if self.managed(local.ty):
            next(f for f in reversed(self.frames) if f.scope).items.append((name, local.ty))
        return name

    def release_until(self, stop: str | None) -> None:
        """Release every frame up to and including the innermost one of kind
        `stop` (for break and continue), or every frame (for return)."""
        for frame in reversed(self.frames):
            self.release_frame(frame)
            if frame.kind == stop:
                break

    # ---- Functions and statements ----

    def function(self, f: FnDecl) -> list[str]:
        self.fn = f
        self.push_frame("function")
        names = []
        for p in f.params:
            # The caller passes each argument owned; the callee releases it.
            names.append(self.local(p.local))
            if self.managed(p.local.ty):
                self.frames[-1].items.append((names[-1], p.local.ty))
        for stmt in f.body.stmts:
            self.stmt(stmt)
        self.pop_frame()
        return [prototype(f, self.layout, names) + " {", *self.lines, "}"]

    def block(self, block: Block, kind: str = "block") -> None:
        """A block's statements, at the current indentation, in a frame."""
        self.push_frame(kind)
        for stmt in block.stmts:
            self.stmt(stmt)
        self.pop_frame()

    def stmt(self, s: Stmt) -> None:
        if isinstance(s, Block):
            self.open("{")
            self.block(s)
            self.close()
            return
        self.emit(f"// line {s.expr.line if isinstance(s, ExprStmt) else s.line}")
        self.push_frame("stmt")
        self.stmt_body(s)
        self.pop_frame()

    def stmt_body(self, s: Stmt) -> None:
        if isinstance(s, ExprStmt):
            self.call_stmt(s.expr)
        elif isinstance(s, Let):
            self.declare(s.local, self.consume(self.expr(s.value)))
        elif isinstance(s, Assign):
            self.assign(s)
        elif isinstance(s, If):
            self.if_stmt(s)
        elif isinstance(s, For):
            # Any statements the condition needs must run on every
            # iteration, so the test goes inside the loop.
            self.open("for (;;) {")
            self.push_frame("body")
            if s.cond is not None:
                self.push_frame("stmt")
                cond = self.scalar(BOOL, self.expr(s.cond).c)
                self.pop_frame()
                self.emit(f"if (!{cond}) break;")
            for stmt in s.body.stmts:
                self.stmt(stmt)
            self.pop_frame()
            self.close()
        elif isinstance(s, ForRange):
            start = self.expr(s.start).c
            # The range is fixed when the loop starts, even if the body
            # changes the variable it was made from.
            end = self.scalar(INT, self.expr(s.end).c)
            i = self.new_temp()
            self.open(f"for (int64_t {i} = {start}; {i} < {end}; {i}++) {{")
            self.push_frame("body")
            self.declare(s.local, i)
            for stmt in s.body.stmts:
                self.stmt(stmt)
            self.pop_frame()
            self.close()
        elif isinstance(s, ForEach):
            self.for_each(s)
        elif isinstance(s, Break):
            self.release_until("body")
            self.emit("break;")
            self.dead = True
        elif isinstance(s, Continue):
            self.release_until("body")
            self.emit("continue;")
            self.dead = True
        elif isinstance(s, Return):
            if s.value is None:
                self.release_until(None)
                self.emit("return;")
            else:
                value = self.consume(self.expr(s.value))
                result = self.new_temp()
                self.emit(f"{self.c_type(s.value.ty)} {result} = {value};")
                self.release_until(None)
                self.emit(f"return {result};")
            self.dead = True
        elif isinstance(s, MatchStmt):
            self.match(s.scrutinee, s.arms, self.arm_stmt)
        else:
            raise AssertionError(f"cannot generate code for {s!r}")

    def if_stmt(self, s: If) -> None:
        cond = self.expr(s.cond).c
        self.open(f"if ({cond}) {{")
        self.block(s.then)
        if s.else_ is None:
            self.close()
            return
        self.close("} else {")
        self.depth += 1
        if isinstance(s.else_, If):
            # `else if`'s condition may need statements of its own, which
            # must only run when the first condition was false.
            self.push_frame("branch")
            self.if_stmt(s.else_)
            self.pop_frame()
        else:
            self.block(s.else_)
        self.close()

    def for_each(self, s: ForEach) -> None:
        """`for x in xs`: the loop keeps its own reference to xs, so the body
        may change xs (that makes a copy) without disturbing the loop."""
        t = s.iterable.ty
        it = self.new_temp()
        self.emit(f"{self.c_type(t)} {it} = {self.consume(self.expr(s.iterable))};")
        self.own(it, t)  # released when the for statement ends
        i = self.new_temp()
        length = f"{it}.len" if t is STR else f"{it}->len"
        self.open(f"for (int64_t {i} = 0; {i} < {length}; {i}++) {{")
        self.push_frame("body")
        if t is STR:
            self.declare(s.local, f"{it}.data[{i}]")
        else:
            elem = self.c_type(s.local.ty)
            name = self.declare(s.local, f"(({elem} *){it}->data)[{i}]")
            self.emit(self.layout.retain(s.local.ty, name))
        for stmt in s.body.stmts:
            self.stmt(stmt)
        self.pop_frame()
        self.close()

    # ---- Assignment and places ----

    def assign(self, s: Assign) -> None:
        # The new value is worked out first; then the place is changed.
        value = self.consume(self.expr(s.value))
        target = s.target
        if isinstance(target, Name):
            name = self.local(target.ref)
            self.emit(self.layout.release(target.ty, name))
            self.emit(f"{name} = {value};")
        elif isinstance(target, Field):
            owner = target.obj.ty
            base = self.place(target.obj)
            member = f"{base}.m_{target.name}"
            if self.layout.is_boxed(owner, target.name):
                # Never write into a box someone else may share: drop this
                # value's box and give the field a new one.
                box = self.layout.box_name(target.ty)
                self.emit(f"{box}_release({member});")
                self.emit(f"{member} = {box}_new({value});")
            else:
                self.emit(self.layout.release(target.ty, member))
                self.emit(f"{member} = {value};")
        else:
            assert isinstance(target, Index)
            container = self.writable(target.obj)
            if isinstance(target.obj.ty, MapType):
                key = self.consume(self.expr(target.index))
                k, v = self.c_type(target.obj.ty.key), self.c_type(target.ty)
                self.emit(f"vela_map_set({container}, {self.addr(k, key)}, {self.addr(v, value)});")
            else:
                index = self.expr(target.index).c
                elem = self.c_type(target.ty)
                self.emit(f"vela_array_set({container}, {index}, {self.addr(elem, value)}, {self.loc(target)});")

    def writable(self, e: Expr) -> str:
        """An lvalue for an array or map about to change, made unique first."""
        place = self.place(e)
        kind = "map" if isinstance(e.ty, MapType) else "array"
        self.emit(f"vela_{kind}_unique(&{place});")
        return place

    def place(self, e: Expr) -> str:
        """A C lvalue for a variable, or a path inside one, that is about to
        be written through. Every shared box or array on the way is copied
        first (copy on write), so the change is seen by this value only."""
        if isinstance(e, Name):
            return self.local(e.ref)
        if isinstance(e, Field):
            base = self.place(e.obj)
            member = f"{base}.m_{e.name}"
            if not self.layout.is_boxed(e.obj.ty, e.name):
                return member
            self.emit(f"{self.layout.box_name(e.ty)}_unique(&{member});")
            return f"{member}->value"
        assert isinstance(e, Index)
        container = self.writable(e.obj)
        if isinstance(e.obj.ty, MapType):
            key = self.expr(e.index).c
            k = self.c_type(e.obj.ty.key)
            return f"(*({self.c_type(e.ty)} *)vela_map_at({container}, {self.addr(k, key)}, {self.loc(e)}))"
        index = self.expr(e.index).c
        return f"(*({self.c_type(e.ty)} *)vela_array_at({container}, {index}, {self.loc(e)}))"

    # ---- Match ----

    def match(self, scrutinee: Expr, arms: list[Arm], body) -> None:
        """An if / else-if chain, one test per arm, in order.

        The checker has proved the arms exhaustive, so if every other arm
        failed the last one must match: it becomes a plain `else`. That
        also tells the C compiler that some arm always runs.
        """
        value = self.expr(scrutinee).c
        t = scrutinee.ty
        for i, arm in enumerate(arms):
            last = i == len(arms) - 1
            self.dead = False  # each arm is reachable, whatever the last one ended with
            if last:
                self.open("} else {" if i else "{")
            else:
                cond = " && ".join(self.tests(arm.pattern, value, t)) or "true"
                self.open(f"{'} else if' if i else 'if'} ({cond}) {{")
            self.push_frame("arm")
            for local, path in self.bindings(arm.pattern, value, t):
                # A binding is a copy of part of the value: it gets a reference
                # of its own.
                name = self.declare(local, path)
                self.emit(self.layout.retain(local.ty, name))
            body(arm)
            self.pop_frame()
            self.depth -= 1
        self.emit("}")
        self.dead = False

    def arm_stmt(self, arm: Arm) -> None:
        if isinstance(arm.body, Block):
            for stmt in arm.body.stmts:
                self.stmt(stmt)
        else:
            self.stmt(arm.body)

    def payload(self, path: str, enum: EnumType, variant, i: int) -> str:
        member = f"{path}.as.m_{variant.name}._{i}"
        return f"{member}->value" if self.layout.is_boxed(enum, variant.name, i) else member

    def tests(self, p: Pattern, path: str, t: Type) -> list[str]:
        """C conditions, all of which hold when the value at `path` matches `p`.

        They are joined with C's `&&`, which stops at the first false one,
        so a payload is only looked at once its tag is known to be right.
        """
        if isinstance(p, (PWild, PBind)):
            return []
        if isinstance(p, PLit):
            lit = p.value
            if isinstance(lit, BoolLit):
                return [path if lit.value else f"!{path}"]
            if isinstance(lit, StrLit):
                return [f"vela_str_eq({path}, VELA_STR({c_string(lit.value)}, {len(lit.value)}))"]
            return [f"{path} == {lit.value}"]
        if isinstance(p, PRange):
            out = []
            # A test that can never fail (a Byte >= 0) would draw a C warning.
            if not (t is BYTE and p.lo.value == 0):
                out.append(f"{path} >= {p.lo.value}")
            if not (t is BYTE and p.hi.value == 255):
                out.append(f"{path} <= {p.hi.value}")
            return out
        assert isinstance(p, PVariant)
        enum, variant = p.ref
        out = [f"{path}.tag == {self.layout.tag(enum, variant.name)}"]
        for i, sub in enumerate(p.args or []):
            out += self.tests(sub, self.payload(path, enum, variant, i), variant.payload[i])
        return out

    def bindings(self, p: Pattern, path: str, t: Type) -> list[tuple[Local, str]]:
        if isinstance(p, PBind):
            return [(p.local, path)]
        if isinstance(p, PVariant):
            enum, variant = p.ref
            out = []
            for i, sub in enumerate(p.args or []):
                out += self.bindings(sub, self.payload(path, enum, variant, i), variant.payload[i])
            return out
        return []

    # ---- Expressions ----

    def expr(self, e: Expr) -> Value:
        """Emit code for `e` and return its value.

        The C expression is always a literal, a variable, a temporary, or a
        field of one of those, so using it has no side effects and its
        position in the C does not matter. A call that produces no value
        returns a Value with the C expression "".
        """
        t = e.ty
        if isinstance(e, (IntLit, ByteLit)):
            return Value(str(e.value), t)
        if isinstance(e, BoolLit):
            return Value("true" if e.value else "false", t)
        if isinstance(e, StrLit):
            return Value(f"VELA_STR({c_string(e.value)}, {len(e.value)})", t, static=True)
        if isinstance(e, Name):
            if isinstance(e.ref, Local):
                return Value(self.local(e.ref), t)
            enum, variant = e.ref  # `None`
            return self.enum_value(enum, variant, [])
        if isinstance(e, Unary):
            operand = self.expr(e.operand).c
            if e.op == "-":
                return Value(self.scalar(INT, f"vela_neg({operand}, {self.loc(e)})"), t)
            return Value(self.scalar(BOOL, f"!{operand}"), t)
        if isinstance(e, Binary):
            return self.binary(e)
        if isinstance(e, Call):
            if isinstance(e.target, tuple):
                enum, variant = e.target
                return self.enum_value(enum, variant, [self.consume(self.expr(a)) for a in e.args])
            if isinstance(e.target, str):
                return self.builtin(e)
            args = [self.consume(self.expr(a)) for a in e.args]
            call = f"{fn_name(e.target)}({', '.join(args)})"
            if t is None:
                self.emit(call + ";")
                return Value("", None)
            return self.store(t, call)
        if isinstance(e, Field):
            if e.variant is not None:
                enum, variant = e.variant
                return self.enum_value(enum, variant, [])
            obj = self.expr(e.obj).c
            member = f"{obj}.m_{e.name}"
            if self.layout.is_boxed(e.obj.ty, e.name):
                member += "->value"
            return Value(member, t)
        if isinstance(e, Index):
            return self.index(e)
        if isinstance(e, Try):
            return self.try_value(e)
        if isinstance(e, Slice):
            obj = self.expr(e.obj).c
            start = self.expr(e.start).c
            end = self.expr(e.end).c
            kind = "str" if t is STR else "array"
            return self.store(t, f"vela_{kind}_slice({obj}, {start}, {end}, {self.loc(e)})")
        if isinstance(e, ArrayLit):
            array = self.store(t, f"vela_array_new({self.layout.descriptor(t.elem)}, {len(e.elems)})")
            elem = self.c_type(t.elem)
            for x in e.elems:
                value = self.consume(self.expr(x))
                self.emit(f"vela_array_push({array.c}, {self.addr(elem, value)});")
            return array
        if isinstance(e, MapLit):
            m = self.store(t, f"vela_map_new({self.layout.descriptor(t.key)}, {self.layout.descriptor(t.value)})")
            k, v = self.c_type(t.key), self.c_type(t.value)
            for en in e.entries:
                key = self.consume(self.expr(en.key))
                value = self.consume(self.expr(en.value))
                self.emit(f"vela_map_set({m.c}, {self.addr(k, key)}, {self.addr(v, value)});")
            return m
        if isinstance(e, StructLit):
            return self.struct_value(e)
        if isinstance(e, Match):
            result = self.new_temp()
            self.emit(f"{self.c_type(t)} {result};")

            def arm_value(arm: Arm) -> None:
                self.emit(f"{result} = {self.consume(self.expr(arm.body))};")

            self.match(e.scrutinee, e.arms, arm_value)
            return self.own(result, t)
        raise AssertionError(f"cannot generate code for {e!r}")

    def try_value(self, e: Try) -> Value:
        """`x?`: if x is an Err (or None), return it from the function now,
        releasing everything that is live, exactly as `return` does.
        Otherwise the value inside the Ok (or Some), borrowed from x.

            if (_t1.tag == Result_Int_Str_Err) {
                vela_str_retain(_t1.as.m_Err._0);
                Result_Bool_Str _t2 = (Result_Bool_Str){ .tag = Result_Bool_Str_Err, .as.m_Err = { ._0 = _t1.as.m_Err._0 } };
                ...releases...
                return _t2;
            }
            ... _t1.as.m_Ok._0 ...
        """
        value = self.expr(e.inner)
        t = e.inner.ty
        result = self.fn.sig.result
        fail, ok = ("Err", "Ok") if t.name == "Result" else ("None", "Some")
        r = self.c_type(result)
        self.open(f"if ({value.c}.tag == {self.layout.tag(t, fail)}) {{")
        returned = self.new_temp()
        if fail == "Err":
            # The error moves into the function's own Result type, which may
            # differ from x's (Result[Int, Str] into Result[Bool, Str]); it
            # gets a reference of its own, since x is released below.
            err = self.payload(value.c, t, t.variant("Err"), 0)
            self.emit(self.layout.retain(t.args[1], err))
            self.emit(f"{r} {returned} = ({r}){{ .tag = {self.layout.tag(result, 'Err')}, "
                      f".as.m_Err = {{ ._0 = {err} }} }};")
        else:
            self.emit(f"{r} {returned} = ({r}){{ .tag = {self.layout.tag(result, 'None')} }};")
        self.release_until(None)
        self.emit(f"return {returned};")
        self.close()
        return Value(self.payload(value.c, t, t.variant(ok), 0), e.ty)

    def index(self, e: Index) -> Value:
        """Reading `xs[i]`, `s[i]` or `m[k]`: the element is copied into a
        temporary, borrowed (it still belongs to the container)."""
        obj = self.expr(e.obj).c
        t = e.obj.ty
        if t is STR:
            index = self.expr(e.index).c
            return Value(self.scalar(BYTE, f"vela_str_at({obj}, {index}, {self.loc(e)})"), BYTE)
        elem = self.c_type(e.ty)
        temp = self.new_temp()
        if isinstance(t, MapType):
            key = self.expr(e.index).c
            k = self.c_type(t.key)
            self.emit(f"{elem} {temp} = *({elem} *)vela_map_at({obj}, {self.addr(k, key)}, {self.loc(e)});")
        else:
            index = self.expr(e.index).c
            self.emit(f"{elem} {temp} = *({elem} *)vela_array_at({obj}, {index}, {self.loc(e)});")
        return Value(temp, e.ty)

    def enum_value(self, enum: EnumType, variant, args: list[str]) -> Value:
        """`(t_Expr){ .tag = ..., .as.m_Add = { ._0 = ..., ._1 = ... } }`, owned.
        `args` are already consumed."""
        fields = [f".tag = {self.layout.tag(enum, variant.name)}"]
        if args:
            values = []
            for i, (arg, pt) in enumerate(zip(args, variant.payload)):
                if self.layout.is_boxed(enum, variant.name, i):
                    arg = f"{self.layout.box_name(pt)}_new({arg})"
                values.append(f"._{i} = {arg}")
            fields.append(f".as.m_{variant.name} = {{ {', '.join(values)} }}")
        return self.store(enum, f"({self.c_type(enum)}){{ {', '.join(fields)} }}")

    def struct_value(self, e: StructLit) -> Value:
        t = e.ty
        assert isinstance(t, StructType)
        values = {}
        for f in e.fields:  # in source order: evaluation is left to right
            value = self.consume(self.expr(f.value))
            if self.layout.is_boxed(t, f.name):
                value = f"{self.layout.box_name(t.fields[f.name])}_new({value})"
            values[f.name] = value
        inits = ", ".join(f".m_{name} = {values[name]}" for name in t.fields)
        return self.store(t, f"({self.c_type(t)}){{ {inits} }}")

    def binary(self, e: Binary) -> Value:
        if e.op in ("&&", "||"):
            # Short-circuit: the right side runs only if it can change the
            # answer, so its code goes inside an `if`, in a frame of its own.
            result = self.scalar(BOOL, self.expr(e.left).c)
            self.open(f"if ({'' if e.op == '&&' else '!'}{result}) {{")
            self.push_frame("branch")
            self.emit(f"{result} = {self.expr(e.right).c};")
            self.pop_frame()
            self.close()
            return Value(result, BOOL)
        left = self.expr(e.left).c
        right = self.expr(e.right).c
        operand = e.left.ty
        if e.op in ARITHMETIC:
            if operand is STR:
                return self.store(STR, f"vela_str_concat({left}, {right})")
            prefix = "vela_byte_" if operand is BYTE else "vela_"
            return Value(self.scalar(e.ty, f"{prefix}{ARITHMETIC[e.op]}({left}, {right}, {self.loc(e)})"), e.ty)
        if operand is STR:
            negate = "!" if e.op == "!=" else ""
            return Value(self.scalar(BOOL, f"{negate}vela_str_eq({left}, {right})"), BOOL)
        if isinstance(operand, EnumType):
            return Value(self.scalar(BOOL, f"{left}.tag {e.op} {right}.tag"), BOOL)
        return Value(self.scalar(BOOL, f"{left} {e.op} {right}"), BOOL)

    def builtin(self, e: Call) -> Value:
        name = e.target
        args = e.args
        if name in ("print", "os.eprint"):
            arg = self.expr(args[0])
            func = PRINT[arg.ty] if name == "print" else PRINT[arg.ty].replace("print", "eprint")
            self.emit(f"{func}({arg.c});")
            return Value("", None)
        if name in RUNTIME_CALLS:
            values = [self.expr(a).c for a in args]
            return self.store(e.ty, f"{RUNTIME_CALLS[name]}({', '.join(values)})")
        if name == "os.exit":
            code = self.expr(args[0]).c
            self.emit(f"vela_os_exit({code}, {self.loc(e)});")
            return Value("", None)
        if name == "strings.builder":
            return self.store(e.ty, "vela_array_new(&vela_type_byte, 0)")
        if name in ("strings.add", "strings.add_byte", "strings.add_int"):
            value = self.expr(args[1]).c  # the value first, then the place: left to right
            b = self.writable(args[0])
            if name == "strings.add_byte":
                self.emit(f"vela_array_push({b}, {self.addr('uint8_t', value)});")
            else:
                self.emit(f"vela_builder_{name[8:]}({b}, {value});")
            return Value("", None)
        if name in ("files.read", "files.write"):
            return self.file_call(e)
        if name == "len":
            arg = self.expr(args[0])
            length = f"{arg.c}.len" if arg.ty is STR else f"{arg.c}->len"
            return Value(self.scalar(INT, length), INT)
        if name == "int":
            return Value(self.scalar(INT, f"(int64_t){self.expr(args[0]).c}"), INT)
        if name == "byte":
            arg = self.expr(args[0]).c
            return Value(self.scalar(BYTE, f"vela_to_byte({arg}, {self.loc(e)})"), BYTE)
        if name == "push":
            value = self.consume(self.expr(args[1]))
            array = self.writable(args[0])
            elem = self.c_type(args[0].ty.elem)
            self.emit(f"vela_array_push({array}, {self.addr(elem, value)});")
            return Value("", None)
        mt = args[0].ty
        assert isinstance(mt, MapType)
        k = self.c_type(mt.key)
        if name == "maps.remove":
            key = self.expr(args[1]).c
            m = self.writable(args[0])
            self.emit(f"(void)vela_map_remove({m}, {self.addr(k, key)});")
            return Value("", None)
        m = self.expr(args[0]).c
        if name == "maps.keys":
            return self.store(e.ty, f"vela_map_keys({m})")
        key = self.expr(args[1]).c
        found = self.new_temp()
        v = self.c_type(mt.value)
        self.emit(f"{v} *{found} = vela_map_find({m}, {self.addr(k, key)});")
        if name == "maps.has":
            return Value(self.scalar(BOOL, f"{found} != NULL"), BOOL)
        # get: Some(a copy of the value), or None.
        opt = e.ty
        result = self.new_temp()
        self.emit(f"{self.c_type(opt)} {result};")
        self.open(f"if ({found}) {{")
        self.emit(f"{result} = ({self.c_type(opt)}){{ .tag = {self.layout.tag(opt, 'Some')}, "
                  f".as.m_Some = {{ ._0 = *{found} }} }};")
        self.emit(self.layout.retain(mt.value, f"{result}.as.m_Some._0"))
        self.close("} else {")
        self.depth += 1
        self.emit(f"{result} = ({self.c_type(opt)}){{ .tag = {self.layout.tag(opt, 'None')} }};")
        self.close()
        return self.own(result, opt)

    def file_call(self, e: Call) -> Value:
        """files.read and files.write. The runtime reports success with a
        bool and fills in the contents or the error message; this builds
        the Result from them."""
        args = [self.expr(a).c for a in e.args]
        r = e.ty
        text = self.new_temp()  # the contents, or the error message
        ok = self.new_temp()
        self.emit(f"vela_str {text} = VELA_STR(\"\", 0);")
        if e.target == "files.read":
            self.emit(f"bool {ok} = vela_files_read({args[0]}, &{text});")
            success = text
        else:
            self.emit(f"bool {ok} = vela_files_write({args[0]}, {args[1]}, &{text});")
            success = f"{args[1]}.len"
        rt = self.c_type(r)
        ok_value = f"({rt}){{ .tag = {self.layout.tag(r, 'Ok')}, .as.m_Ok = {{ ._0 = {success} }} }}"
        err_value = f"({rt}){{ .tag = {self.layout.tag(r, 'Err')}, .as.m_Err = {{ ._0 = {text} }} }}"
        return self.store(r, f"{ok} ? {ok_value} : {err_value}")

    def call_stmt(self, e: Expr) -> None:
        """A call whose result, if any, is thrown away (at the statement's end)."""
        self.expr(e)


def c_string(data: bytes) -> str:
    """A C string literal for any bytes: a file name or a Vela string."""
    out = []
    for byte in data:
        ch = chr(byte)
        if ch in '"\\?':
            # `?` too: with -std=c11, `??/` and friends are trigraphs.
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")  # octal escapes stop after 3 digits
    return '"' + "".join(out) + '"'
